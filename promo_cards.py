def _load_font(size: int, bold: bool = False):
    """Carga una fuente TTF disponible en Linux (Render) o Windows, con fallback seguro a Pillow."""
    candidates = (
        [
            "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
            "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
            "C:/Windows/Fonts/arialbd.ttf",
            "C:/Windows/Fonts/segoeui.ttf",
        ]
        if bold
        else [
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
            "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
            "C:/Windows/Fonts/arial.ttf",
            "C:/Windows/Fonts/segoeui.ttf",
        ]
    )
    for path in candidates:
        if os.path.exists(path):
            try:
                return ImageFont.truetype(path, size=size)
            except Exception:
                pass
    try:
        return ImageFont.load_default(size=size)
    except Exception:
        return ImageFont.load_default()


def _paste_rounded_logo(
    canvas: Image.Image,
    raw_bytes: bytes,
    box: tuple[int, int, int, int],
    radius: int = 24,
    bg_color=None,
    padding: int = 12,
    auto_crop_white: bool = False,
) -> None:
    x, y, w, h = box
    logo = Image.open(io.BytesIO(raw_bytes)).convert("RGBA")
    if auto_crop_white:
        rgb = logo.convert("RGB")
        # Encuentra el bounding box no-blanco para que el sticker ocupe mejor el marco
        mask_nonwhite = rgb.point(lambda p: 255 if p < 245 else 0).convert("L")
        bbox = mask_nonwhite.getbbox()
        if bbox:
            logo = logo.crop(bbox)
    if bg_color is None:
        bg_color = logo.getpixel((2, 2))
    base = Image.new("RGBA", (w, h), bg_color)
    logo.thumbnail((w - padding, h - padding), Image.Resampling.LANCZOS)
    ox = (w - logo.width) // 2
    oy = (h - logo.height) // 2
    base.paste(logo, (ox, oy), logo)

    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, w - 1, h - 1], radius=radius, fill=255)
    canvas.paste(base, (x, y), mask)


