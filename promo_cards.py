    """Genera tarjeta PNG promocional de SNAP! Stock, TCG Fans y Lo de Charly."""
    W, H = 880, 320
    img = Image.new("RGBA", (W, H), (16, 19, 40, 255))
    draw = ImageDraw.Draw(img)

    for y in range(H):
        r = int(16 + (y / H) * 24)
        g = int(19 + (y / H) * 14)
        b = int(42 + (y / H) * 24)
        draw.line([(0, y), (W, y)], fill=(r, g, b, 255))

    draw.rounded_rectangle([10, 10, W - 11, H - 11], radius=22, outline=(255, 107, 53, 240), width=3)
    draw.rounded_rectangle([24, 24, W - 24, H - 24], radius=16, fill=(26, 29, 58, 225), outline=(255, 159, 28, 110), width=2)

    logo_bytes = base64.b64decode(SNAP_LOGO_B64)
    _paste_rounded_logo(img, logo_bytes, (48, 56, 204, 204), radius=24, bg_color=(255, 255, 255, 255), padding=18, auto_crop_white=True)
    draw.rounded_rectangle([48, 56, 252, 260], radius=24, outline=(255, 107, 53, 235), width=3)

    font_tag = _load_font(15, bold=True)
    font_title = _load_font(38, bold=True)
    font_sub = _load_font(24, bold=True)
    font_info = _load_font(19, bold=False)

    draw.rounded_rectangle([280, 50, 615, 84], radius=17, fill=(255, 107, 53, 245))
    draw.text((298, 57), "TIENDA POKEMON TCG  •  ARGENTINA", font=font_tag, fill=(255, 255, 255, 255))

    draw.text((280, 98), "SNAP! STOCK & TCG FANS", font=font_title, fill=(255, 255, 255, 255))
    draw.text((280, 148), "Cartón jugable y brillante", font=font_sub, fill=(255, 210, 76, 255))

    draw.line([(280, 192), (825, 192)], fill=(255, 159, 28, 120), width=2)
    draw.text((280, 208), "catalogo.snap-stock.com/snap/catalogo", font=font_info, fill=(190, 230, 255, 255))
    draw.text((280, 238), "Sábados en Lo de Charly (Chaco 21)", font=_load_font(19, bold=True), fill=(255, 235, 200, 255))

    buf = io.BytesIO()
    img.convert("RGB").save(buf, format="PNG", optimize=True)
    return buf.getvalue()
