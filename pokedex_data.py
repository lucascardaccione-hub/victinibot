def resolve_wild_form_for_level(species_id: int, wild_level: int) -> tuple[int, str, str, str]:
    """
    Ajusta la especie salvaje al nivel del encuentro:
    - Si salió una evolución cuyo nivel mínimo supera `wild_level`, retrocede a su pre-evolución.
    - Si salió una pre-evolución y `wild_level` alcanza su nivel de evolución, puede aparecer evolucionada.
    """
    cur_id = species_id
    # 1. Retroceder si el nivel salvaje aún no alcanza el nivel evolutivo de esta forma
    for _ in range(3):
        parent_info = LEVEL_EVO_PARENTS.get(cur_id)
        if parent_info and wild_level < parent_info[1]:
            cur_id = parent_info[0]
        else:
            break

    # 2. Avanzar si el nivel salvaje alcanza evoluciones por nivel
    for _ in range(3):
        opts = LEVEL_EVOLUTIONS.get(cur_id)
        if not opts:
            break
        eligible = [o for o in opts if wild_level >= o["min_level"]]
        if not eligible:
            break
        chosen = random.choice(eligible)
        cur_id = chosen["to_id"]

    return SPECIES_BY_ID[cur_id]
